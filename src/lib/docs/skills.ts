/**
 * The cloud courses are one course in two vocabularies: the task `<p>-w<n>-<role>`
 * exists as `az-…` on Azure and `aws-…` on AWS, in the entry (weeks 1–4),
 * associate (5–8) and professional (9–12) course of each. One table, both maps.
 */
export const CLOUD_COURSES: Record<string, [prefix: string, weeks: [number, number]]> = {
  'azure-fundamentals': ['az', [1, 4]],
  'azure-administrator': ['az', [5, 8]],
  'azure-devops': ['az', [9, 12]],
  'aws-cloud-practitioner': ['aws', [1, 4]],
  'aws-solutions-architect': ['aws', [5, 8]],
  'aws-devops': ['aws', [9, 12]],
};

/** `{ 'w5-arch': ids }` → per cloud course, `{ 'az-w5-arch': ids }`. */
export function cloudMap<T>(table: Record<string, T>): Record<string, Record<string, T>> {
  const out: Record<string, Record<string, T>> = {};
  for (const [courseId, [prefix, [from, to]]] of Object.entries(CLOUD_COURSES)) {
    out[courseId] = {};
    for (const [key, value] of Object.entries(table)) {
      const week = Number(/^w(\d+)-/.exec(key)?.[1]);
      if (week >= from && week <= to) out[courseId][`${prefix}-${key}`] = value;
    }
  }
  return out;
}

