// CISSP capstone (ISC2): "Six Releases" (R101, rewritten R102).
//
// The team is the security function for Ridgeline's migration to the cloud
// Service Hub. Every week ships a complete program as eight domain sheets
// (D1–D8), raising a 0–32 maturity score, adding control statements and
// closing planted weaknesses, and ending federal-ready. The spec is written
// for one learner; the platform's three-role shape splits the eight sheets:
//
//   Governance & Risk      D1 Governance · D2 Assets · D6 Assessment
//   Architecture & Network D3 Architecture · D4 Network · D8 Software
//   Identity & Operations  D5 Identity · D7 Operations
//
// R102 — every step is written to one contract: WHERE it happens, one line,
// two to four numbered actions with Ridgeline's own example values, the
// command with every flag explained and what it prints, the output annotated
// with what proves it, the page to read and what to look for there, two
// "if it breaks" fixes, and one short why. The lab the spec names is not
// built yet: containers on one Linux machine play the cloud account, and the
// instructor supplies the sample repository, the old-server image and the
// planted dataset. No gatekeeping: every week is open; the gates still mark
// each release. Forms: docs/cisspDeliverables.ts; picture: docs/cisspContent.ts.

