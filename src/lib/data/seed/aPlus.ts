/**
 * CompTIA A+ — the Capstone Bench.
 *
 * A used desktop PC arrives at the help desk with no record and a fault. The
 * team brings it back on a real bench, the way a field technician would: open
 * the case, read what is really inside, work the fault with the six-step
 * troubleshooting method, take a full disk image BEFORE changing anything,
 * install and baseline the operating system, prove the image restores, run a
 * week of support tickets against injected faults, secure the machine, time
 * one more restore, and hand it over with an as-built record and a chain of
 * custody for every artifact.
 *
 * REAL EQUIPMENT. One second-hand desktop per team (see `costs.ts`), a spare
 * drive, a USB stick, an external drive for images, a screwdriver and a strap.
 * The physical steps are form steps with a `danger` line where the action is
 * irreversible; the proof steps run real commands on a Linux live USB and in
 * PowerShell, with the output pasted back. Nothing here is a slide.
 *
 * THE RULE THE COURSE TEACHES: image first. Every step that changes the disk
 * sits after an image step, and the Week 2 and Week 4 restores are timed with
 * two clock readings, exactly as Server+ proves its disaster recovery.
 *
 * ONE SHARED TRACK, FOUR FOCUSES (`sharedTrack: true`, `noGatekeeping: true`,
 * like Server+ and CCNA). Everyone works every task on the team's PC; the
 * focus decides which record a member leads and reviews. Week 0 is
 * preparation (`setup: true`) and is never graded.
 */

